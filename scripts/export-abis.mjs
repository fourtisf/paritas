// Copies contract ABIs from Foundry's build output into packages/shared/src/abi.ts
// so the API, the indexer and the web app all use exactly what was compiled.
// Run after every contract change:  npm run abi   (from the repo root, after `forge build`)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const contracts = [
  ["SwapRouter", "swapRouterAbi"],
  ["AnchorVault", "anchorVaultAbi"],
  ["VaultFactory", "vaultFactoryAbi"],
  ["ParamController", "paramControllerAbi"],
  ["SessionController", "sessionControllerAbi"],
  ["OracleRouter", "oracleRouterAbi"],
  ["EligibilityRegistry", "eligibilityRegistryAbi"],
  ["RfqSettlement", "rfqSettlementAbi"],
  ["FeeCollector", "feeCollectorAbi"],
  ["UniswapV3Adapter", "uniswapV3AdapterAbi"],
];

let ts = "// GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n\n";
const errors = new Map();
for (const [name, exportName] of contracts) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
  const abi = JSON.parse(readFileSync(file, "utf8")).abi;
  for (const item of abi) if (item.type === "error") errors.set(item.name, item);
  ts += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
ts += `/** Every custom error any Paritas contract can revert with (for decodeErrorResult). */\n`;
ts += `export const paritasErrorsAbi = ${JSON.stringify([...errors.values()], null, 2)} as const;\n`;
writeFileSync(join(root, "packages", "shared", "src", "abi.ts"), ts);
console.log(`abi.ts: ${contracts.length} contracts, ${errors.size} errors`);
